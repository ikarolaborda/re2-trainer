import Foundation

/// A static pointer chain: `moduleBase + anchor`, then deref-and-add each offset.
struct Chain {
    let anchor: UInt64
    let offsets: [UInt64]

    func resolve(_ mem: ProcessMemory, moduleBase: UInt64) -> UInt64? {
        var addr = moduleBase &+ anchor
        for off in offsets {
            guard let p = mem.readU64(addr) else { return nil }
            addr = p &+ off
        }
        return addr
    }
}

